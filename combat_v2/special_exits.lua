function M.new(io)
  assert(type(io)=='table' and type(io.send)=='function' and type(io.gate)=='function')
  local t={serial=0,pending=nil,plan=nil,index=1,active=false,attempts={},history={}}
  function t:cancel(reason)
    self.active=false;self.reason=reason or 'cancelled' -- issued pending is deliberately retained
  end
  function t:begin(p,c)
    if self.pending or self.active then return false,'busy' end
    if not p or not p.returnproof or p.returnproof.graph~=c.graph or p.returnproof.session~=c.session or p.returnproof.epoch~=c.epoch then return false,'no current return proof' end
    if p.session~=c.session or p.epoch~=c.epoch or p.graph~=c.graph or c.room~=p.from then return false,'scope mismatch' end
    self.plan=copy(p);self.index=1;self.attempts={};self.floor=nil;self.active=true;return true
  end
  local function finish(self)
    local p=self.pending
    if not p or not p.finalized or not p.sent or not p.evidence then return false end
    self.floor={seq=p.evidence.seq,prompt=p.evidence.prompt or p.prompt}
    self.history[#self.history+1]=copy(p);self.pending=nil;self.index=self.index+1
    if self.index>#self.plan.steps then self.active=false;self.reason='arrived' end
    return true
  end
  function t:step(c)
    if self.pending then return false,'pending' end
    if not self.active then return false,'inactive' end
    local plan=self.plan
    if c.session~=plan.session or c.epoch~=plan.epoch or c.graph~=plan.graph then self:cancel('new intent/session/graph');return false,self.reason end
    if not c.fresh or c.room~=plan.from or not c.ready or not c.safe or not c.authorized or not c.return_available then return false,'fresh readiness required' end
    if type(c.seq)~='number' or type(c.prompt)~='number' then return false,'missing chronology' end
    local floor=self.floor
    if floor and (c.seq<floor.seq or c.prompt<=floor.prompt) then return false,'new post-action prompt required' end
    if not io.gate(copy(plan),copy(c)) then return false,'native owner/capability gate' end
    local s=plan.steps[self.index];local count=(self.attempts[self.index] or 0)+1
    if count>2 then self:cancel('retry exhausted');return false,self.reason end
    self.attempts[self.index]=count;self.serial=self.serial+1
    local p={serial=self.serial,session=c.session,epoch=c.epoch,from=plan.from,to=plan.to,command=s.command,
      ack=s.ack,seq=c.seq,prompt=c.prompt,index=self.index,finalized=false,sent=false}
    self.pending=p -- owns action BEFORE transport or any reentrant callback
    local ok,result=pcall(io.send,p.command,copy(p))
    p.finalized=true;p.sent=ok and result==true
    if not p.sent then p.unknown=true;self:cancel('transport unknown') end
    finish(self);return p.sent,p.sent and 'issued' or 'transport unknown'
  end
  function t:evidence(e)
    local p=self.pending
    if not p or type(e)~='table' or e.serial~=p.serial or e.session~=p.session or e.command~=p.command then return false end
    if type(e.seq)~='number' or e.seq<=p.seq then return false end
    if p.ack=='arrival' then
      if e.kind~='Room.Info' or e.room~=p.to or e.area_verified~=true then return false end
    else
      if e.kind~='door-proof' or e.room~=p.from or e.state~=p.ack or not e.own_response or not e.readback or type(e.prompt)~='number' or e.prompt<=p.prompt then return false end
    end
    p.evidence=copy(e);return finish(self)
  end
  -- Explicit reviewed failure only: never timeout/elapsed settlement or automatic resending.
  function t:review_failed(e,c)
    local p=self.pending
    if not p or not p.finalized or not p.sent or p.evidence then return false end
    if e.serial~=p.serial or e.session~=p.session or e.command~=p.command or e.room~=p.from or not e.own_rejection or not provenance(e.provenance) then return false end
    if type(e.seq)~='number' or e.seq<=p.seq or c.session~=p.session or c.room~=p.from or not c.fresh or type(c.seq)~='number' or c.seq<=e.seq or type(c.prompt)~='number' or c.prompt<=p.prompt then return false end
    self.floor={seq=c.seq,prompt=c.prompt}
    p.rejection=copy(e);self.history[#self.history+1]=copy(p);self.pending=nil
    -- STOP remains stopped; no grant renewal, budget reset or automatic send.
    return true
  end
  function t:barrier() return self.pending~=nil end
  function t:status() return copy({active=self.active,index=self.index,pending=self.pending,reason=self.reason,serial=self.serial}) end
  return t
end

