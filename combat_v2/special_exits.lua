-- Capabilities are certificates from the native adapter, NOT inferred from map flags.
function M.plan(e,c)
  if type(e)~='table' or type(c)~='table' or not id(e.from) or not id(e.to) or e.from==e.to then return nil,'bad endpoints' end
  if not provenance(e.provenance) or not provenance(c.provenance) then return nil,'unreviewed provenance' end
  if not c.fresh or c.room~=e.from or not c.session or not c.epoch or not c.graph then return nil,'stale capability' end
  if not c.safe or not c.authorized or not c.return_available then return nil,'unsafe/unconsented/no return capability' end
  local d=long[e.direction] or e.direction
  local steps,req={},{}
  local function add(cmd,ack) steps[#steps+1]={command=cmd,ack=ack} end
  if e.kind=='ordinary' or e.kind=='swim' or e.kind=='door' then
    if not dirs[d] then return nil,'bad direction' end
    if e.kind=='ordinary' and c.terrain~='foot' then return nil,'terrain needs adapter' end
    if e.kind=='swim' then
      if not c.swim_skill or not c.aquatic_survival or c.terrain~='water' then return nil,'swimming not certified' end
      req={'swim_skill','aquatic_survival'}; add('swim '..d,'arrival')
    elseif e.kind=='door' then
      -- No numeric getDoors/XML door interpretation: adapter supplies reviewed state.
      if c.door_state=='locked' then
        if not c.key_available or not c.unlock_permission then return nil,'unlock not certified' end
        req={'key_available','unlock_permission'}; add('unlock door '..d,'unlocked'); add('open door '..d,'open')
      elseif c.door_state=='closed' then add('open door '..d,'open')
      elseif c.door_state~='open' then return nil,'unknown door state' end
      if c.terrain~='foot' then return nil,'door terrain not certified' end
      add(d,'arrival')
    else add(d,'arrival') end
  elseif e.kind=='climb' or e.kind=='portal' then
    local cmd=exact[e.from..':'..e.to]
    if not cmd or cmd~=e.command or (e.kind=='climb')~=(cmd:sub(1,6)=='climb ') then return nil,'unreviewed special command/endpoints' end
    if not c.object_present or not c.special_available then return nil,'special unavailable' end
    if e.kind=='climb' and not c.climb_skill then return nil,'climbing not certified' end
    req={'object_present','special_available'}; add(cmd,'arrival')
  else return nil,'unsupported special class' end
  return {from=e.from,to=e.to,kind=e.kind,command=steps[#steps].command,requirements=req,
    provenance=copy(e.provenance),steps=steps,session=c.session,epoch=c.epoch,graph=c.graph,
    returnproof=nil,reviewed=true}
end
