local wet_labels={water=true,ocean=true,sea=true,lake=true,river=true,['freshwater']=true,['shallow water']=true,['deep water']=true,underwater=true,['ocean floor']=true}
function M.water_environment(env)
 local m=mmp or {};local label=(m.envidsr or {})[env]or(m.envidsr or {})[tostring(env)]
 if not label then for k,v in pairs(m.envids or {})do if tostring(v)==tostring(env)then label=k;break end end end
 return type(label)=='string' and wet_labels[label:lower()]==true,label
end
-- Pure source-evidence validator. plan is FUTURE topology, never a current FULL.
-- This helper does not attach itself: a native read-only adapter must supply e.
function M.evidence_capability(meta,e,phase)
 if type(e)~='table' or not e.session or not e.epoch or not e.graph then return nil,'missing session/intent/graph evidence'end
 if meta.kind~='swim'then return nil,'native special topology unregistered or unreviewed'end
 if not provenance(e.provenance)then return nil,'missing reviewed evidence provenance'end
 if not e.skill or e.skill.session~=(e.learning_session or e.session)or e.character and e.skill.character~=e.character or e.skill.learned~=true or e.skill.name~='Swimming' or not provenance(e.skill.provenance)then return nil,'missing learned Swimming evidence'end
 local surface={river=true,freshwater=true}
 local function terrain(x)return type(x)=='table'and type(x.label)=='string'and surface[x.label:lower()]==true end
 local a,b=e.source,e.target
 if not a or not b then return nil,'missing native endpoints'end
 if a.water and not terrain(a)or b.water and not terrain(b)then return nil,'submerged/deep aquatic survival not certified'end
 if not e.survival or e.survival.session~=(e.learning_session or e.session)or e.character and e.survival.character~=e.character or e.survival.treading_learned~=true or e.survival.fluidswim_learned~=true or not provenance(e.survival.provenance)then return nil,'missing passive Treading/FluidSwim evidence'end
 for _,x in ipairs({a or {},b or {}})do
  local weight=tonumber(x.weight)
  if x.area~=meta.from_area or x.locked~=false or not weight or not(weight>=0 and weight<=1)or x.private~=false then return nil,'unsafe native endpoint/area/lock/weight/privacy'end
 end
 if tostring(a.id)~=tostring(meta.from)or tostring(b.id)~=tostring(meta.to)or (a.exits or {})[meta.direction]~=meta.to or a.door_open~=true or b.same_pair_door_open~=true then return nil,'native endpoint/exit/door mismatch'end
 if a.water~=true and b.water~=true then return nil,'not a reviewed aquatic edge'end
 if phase=='dispatch'then
  local d=e.dispatch
  if not d or d.mounted~=false or d.room~=meta.from or d.session~=e.session or d.epoch~=e.epoch or d.graph~=e.graph or d.room_info_current~=true or d.core_full_current~=true or d.players_current~=true or d.navigation_grant~=true or not(d.real_modes_off==true or d.bash_walk_current==true)or d.ready~=true or d.owners_settled~=true then return nil,'missing fresh navigation-only dispatch proof'end
 elseif phase~='plan'then return nil,'explicit plan/dispatch phase required'end
 return {fresh=true,room=meta.from,session=e.session,epoch=e.epoch,graph=e.graph,safe=true,authorized=true,return_available=true,terrain='water',swim_skill=true,aquatic_survival=true,provenance=e.provenance}
end
-- Finite public SURFACE batch from native-map.json (not all Freshwater rooms).
-- Deep-water names 20305/20306 and beneath/shaft 19905/19906 are NOT surface.
-- Exact ID/name/area review prevents cottages/houses becoming an implicit permit.
local surface_public={
 [20301]={27,'Rolling grasslands nearing a small lake'},
 [20302]={27,'Amidst the lily pads'},[20303]={27,'In a placid lake'},
 [20304]={27,'Clear waters of a placid lake'},
 [20307]={27,'Approaching the shallows of a placid lake'},[20308]={27,'A small inlet by a waterfall'},
 [19904]={93,'A fairly opalescent lake'},[19893]={93,'A patch of flora'},
 [19899]={93,'A clearing before a lake'},[19898]={93,'Muddy land at the edge of a lake'},
 [19896]={93,'A moist copse near a lake'},[19894]={93,'A sandy stretch of bleached trees'}
}
function M.surface_endpoint(c,id)
 local review=surface_public[tonumber(id)]
 if not review or tonumber(id)==56349 or type(getRoomName)~='function'or getRoomName(id)~=review[2]or getRoomArea(id)~=review[1]then return nil end
 local water,label=M.water_environment(getRoomEnv(id))
 if water then if label~='River'and label~='Freshwater'and label~='river'and label~='freshwater'then return nil end
 elseif not c.tour_boot or not c.tour_boot.dry_environment(getRoomEnv(id))then return nil end
 local exits,doors=getRoomExits(id),getDoors(id)
 if type(exits)~='table'or type(doors)~='table'then return nil end
 local out={};for k,v in pairs(exits)do out[long[k]or k]=tonumber(v)end
 local ds={};for k,v in pairs(doors)do ds[long[k]or k]=v end
 return {id=tonumber(id),area=review[1],private=false,water=water==true,label=label,
  exits=out,doors=ds,locked=roomLocked(id),weight=getRoomWeight(id)}
end
local surface_providers=setmetatable({},{__mode='k'})
function M.compose_surface_probe(c,probe)
 local current=c.special_exit_capability
 if type(probe)~='function'or surface_providers[c]~=current then return false,'existing capability provider preserved'end
 local provider=function(owner,meta,phase,emergency)
  if c.mode=='OFF'and c.current.mode=='OFF'and c.runner.mode=='OFF'then return probe(owner,meta,phase)end
  return current(owner,meta,phase,emergency)
 end
 c.special_exit_capability=provider;surface_providers[c]=provider;return true,provider
end
function M.bind_surface_provider(c)
 if c.special_exit_capability~=nil then return false,'existing capability provider preserved'end
 local current=c.current
 c.special_exit_capability=function(owner,meta,phase,emergency)
  if owner~=c or c.current~=current or meta.kind~='swim'then return nil,'surface provider owner/kind mismatch'end
  local o=current.class_observations;local t=o and o.survival
  if not t or t.session~=o.session or t.character~=o.character or not t.syntax then return nil,'fresh native Survival reprime required'end
  for _,k in ipairs({'swimming','treading','fluidswim'})do if not t.skills[k]or t.skills[k].known~=true then return nil,'missing character-wide learned '..k end end
  local a,b=M.surface_endpoint(c,meta.from),M.surface_endpoint(c,meta.to)
  if not a or not b then return nil,'endpoint outside reviewed public surface batch'end
  local d=long[meta.direction]or meta.direction
  a.door_open=not a.doors[d]or tonumber(a.doors[d])==0
  local back=({n='s',s='n',e='w',w='e',ne='sw',sw='ne',se='nw',nw='se',u='d',d='u'})[d]
  b.same_pair_door_open=true
  if back and b.exits[back]==meta.from then b.same_pair_door_open=not b.doors[back]or tonumber(b.doors[back])==0 end
  local w=c.walker.state(current)
  local p={source='native-map.json public surface review + original owned native Survival records',digest='7b13ab218ab71fa6bba8b3d7ada5d9e5c6b22f26b201ed597d30f312cd41f9c4',reviewed=true}
  local e={session=w.movement_session,epoch=o.epoch,graph=M,learning_session=o.session,character=o.character,
   source=a,target=b,provenance=p,
   skill={name='Swimming',learned=true,session=t.session,character=t.character,record=t.skills.swimming.record,syntax=t.syntax,provenance=p},
   survival={session=t.session,character=t.character,treading_learned=true,fluidswim_learned=true,
    treading=t.skills.treading.record,fluidswim=t.skills.fluidswim.record,provenance=p}}
  if phase=='dispatch'then
   if not o.class or o.class.value~=current.player.class or current.player.class=='Shapeshifter'then return nil,'current native class/form readiness unverified'end
   local g=w.graph;local hop=g and g.special_edges and g.special_edges[tostring(meta.from)]and g.special_edges[tostring(meta.from)][d]
   local info=gmcp and gmcp.Room and gmcp.Room.Info;local policy=current.policy or {};local i=w.inspection
   local grant=c.mode=='BASH'and current.mode=='BASH'and c.runner.mode=='BASH'and w.active==true and w.enabled==true
    and not(w.pending or w.dispatching or w.arrival_hold or w.fault)and hop and hop.kind=='swim'and hop.to==tostring(meta.to)
   if c.tour and c.tour.state.slot then
    local ts=c.tour.state;local slot=ts.slot
    grant=grant and ts.phase=='hunt'and ts.grant~=nil and slot.grant==ts.grant and slot.token==w.offers
     and slot.epoch==(w.intent_epoch or 0)and slot.active_graph==g and c.tour.io.scope(ts.grant)==true
   end
   local escaping=emergency~=nil and emergency==c.bash_emergency and c.walker.emergency_valid(c,emergency,hop)==true
   if emergency~=nil and not escaping then return nil,'private emergency grant unavailable'end
   local ready=c.walker_boot.surface_ready(c,escaping and emergency or nil,hop)
   local full=o.cache['Char.Items.List'];local prompt=o.cache['native.prompt']
   local later_prompt=full and prompt and prompt.seq>full.seq
   e.dispatch={room=tonumber(current.room.id),session=e.session,epoch=e.epoch,graph=e.graph,
    mounted=current.player.mounted,
    room_info_current=info and tostring(info.num)==tostring(meta.from)and info.area==current.room.area and tostring(normalized(info.exits,d))==tostring(meta.to),
    core_full_current=c.areas.fresh(current)==true and later_prompt and(escaping or i and i.items==current.room.items and i.version==current.room.item_version and i.sequence==w.room_sequence),
    players_current=policy.players_known==true and policy.players_room==current.room.id and policy.players==policy.native_players and type(policy.players_version)=='number'and policy.players_version>0,
    navigation_grant=not not grant,bash_walk_current=not not grant,ready=ready==true,owners_settled=ready==true}
  end
  return M.evidence_capability(meta,e,phase)
 end
 surface_providers[c]=c.special_exit_capability
 return true
end
return M
